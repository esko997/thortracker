import org.jetbrains.kotlin.gradle.dsl.JvmTarget

plugins {
    id("org.jetbrains.kotlin.multiplatform")
    id("org.jetbrains.kotlin.plugin.serialization")
}

// org.thortracker.BuildInfo: the app version Help → About and the diagnostics show on every frontend. The version
// stays in app/build.gradle.kts, its one source (CI and tools/release.sh read it there with the same patterns).
val appBuildScript = rootProject.file("app/build.gradle.kts")
val buildInfoDir = layout.buildDirectory.dir("generated/buildinfo/kotlin")
val generateBuildInfo by tasks.registering {
    inputs.file(appBuildScript)
    outputs.dir(buildInfoDir)
    doLast {
        val script = appBuildScript.readText()
        fun field(pattern: String) = Regex(pattern, RegexOption.MULTILINE).find(script)?.groupValues?.get(1)
            ?: throw GradleException("app/build.gradle.kts has no line matching $pattern")
        val name = field("""^ *versionName = "(.*)"$""")
        val code = field("""^ *versionCode = ([0-9]+)$""")
        val file = buildInfoDir.get().file("org/thortracker/BuildInfo.kt").asFile
        file.parentFile.mkdirs()
        file.writeText("""
            |package org.thortracker
            |
            |/** Generated by core/build.gradle.kts from app/build.gradle.kts: the version every frontend shows. */
            |object BuildInfo {
            |    const val VERSION_NAME = "$name"
            |    const val VERSION_CODE = $code
            |}
            |""".trimMargin())
    }
}

// Platform-independent tracker core: document model, hUGE rules/lowering/export, editor and keymap. The Android app
// consumes the JVM target; linuxX64 is the Kotlin/Native target for the Steam Deck frontend.
kotlin {
    jvm {
        compilerOptions { jvmTarget.set(JvmTarget.JVM_17) }
    }
    linuxX64()
    linuxArm64()

    sourceSets {
        commonMain {
            kotlin.srcDir(generateBuildInfo)
            dependencies {
                // api: @Serializable model classes expose generated serializers to frontends.
                api("org.jetbrains.kotlinx:kotlinx-serialization-json:1.7.3")
            }
        }
        commonTest.dependencies {
            implementation(kotlin("test"))
        }
        jvmTest.dependencies {
            implementation("junit:junit:4.13.2")
        }
    }
}

tasks.named<Test>("jvmTest") { useJUnit() }
