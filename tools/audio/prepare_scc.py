"""Generates the SCC engine's tables, the Kotlin contract object and the host test's fixtures (pure Python 3, no
dependencies):

  app/src/main/cpp/generated/scc_tables.h   SC_DIV (period divider per 1/64 semitone, Q8) and SC_SINE (vibrato)
  core/.../backend/SccPlayerImage.kt        the image layout, limits, effect codes, period table, clock, seek and GD3
                                            constants and the loader's messages for the Kotlin lowering and validator,
                                            parsed from the engine's C headers and scc_image.c
  app/src/test/cpp/scc_test_song.h          test images (tools/audio/scc/scc_song.py), the reference player's
                                            (tools/audio/scc/scc_ref.py) batches and VGM facts, corruption offsets

    python3 tools/audio/prepare_scc.py
Rerun after changing the specification (docs/AUDIO_ENGINE.md "SCC and SCC+"), the engine headers, the reference
player or the test song."""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(HERE, "scc"))

import scc_ref  # noqa: E402
import scc_song  # noqa: E402

TICKS = 1500
VGM_MAX_TICKS = 36000
CPP = os.path.join(ROOT, "app/src/main/cpp")
TABLES = os.path.join(CPP, "generated/scc_tables.h")
FIXTURE = os.path.join(ROOT, "app/src/test/cpp/scc_test_song.h")
KOTLIN = os.path.join(ROOT, "core/src/commonMain/kotlin/org/thortracker/backend/SccPlayerImage.kt")
LETTERS = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ"


def c_array(ctype, name, size, values, per_line=24):
    values = list(values) or [0]
    lines = ["static const %s %s[%s] = {" % (ctype, name, size if size is not None else len(values))]
    for i in range(0, len(values), per_line):
        lines.append("    " + ",".join("%d" % v for v in values[i:i + per_line]) + ",")
    lines.append("};")
    return "\n".join(lines)


def used(image):
    """The image up to its last non-zero byte (the test zero-pads it back to 65536)."""
    return image[:len(image.rstrip(b"\0"))]


def fnv64(data):
    h = 0xCBF29CE484222325
    for b in data:
        h = ((h ^ b) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


