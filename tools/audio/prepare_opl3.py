#!/usr/bin/env python3
"""Generates the OPL3 engine's tables and the host test's fixtures (pure Python 3, no dependencies):

  app/src/main/cpp/generated/opl3_tables.h   pitch (F-number per 1/64 semitone) and vibrato sine tables
  app/src/test/cpp/opl3_test_song.h          test images (tools/audio/opl3/opl3_song.py) and the reference
                                             player's writes and VGM (tools/audio/opl3/opl3_ref.py)
  core/.../backend/Opl3PlayerImage.kt        the image layout, limits, effect codes and loader messages for the
                                             Kotlin lowering and validator, parsed from the engine's C headers

    python3 tools/audio/prepare_opl3.py
Rerun after changing the player specification, the reference player or the test song."""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(HERE, "opl3"))

import opl3_ref  # noqa: E402
import opl3_song  # noqa: E402

TICKS = 1500
VGM_MAX_TICKS = 36000


def c_bytes(name, data):
    lines = ["static const unsigned char %s[%d] = {" % (name, len(data))]
    for i in range(0, len(data), 24):
        lines.append("    " + ",".join("%d" % b for b in data[i:i + 24]) + ",")
    lines.append("};")
    return "\n".join(lines)


def used(image):
    """Bytes up to the end of the pattern data (the rest of an image is zero)."""
    size = image[14] | image[15] << 8
    end = opl3_song.OFF_DATA + size
    assert not any(image[end:])
    return image[:end]


def trace_arrays(prefix, image_bytes):
    tr = opl3_ref.trace(opl3_ref.Image(image_bytes), TICKS)
    offsets, regs, vals, pos, splits = [0], [], [], [], []
    for p, writes, split in tr:
        for reg, val in writes:
            regs.append(reg)
            vals.append(val)
        offsets.append(len(regs))
        splits.append(split)
        pos.extend(p if p is not None else (-1, -1, -1))
    out = []
    out.append("static const int %s_offsets[%d] = {%s};" % (prefix, len(offsets), ",".join(map(str, offsets))))
    out.append("static const unsigned short %s_regs[%d] = {%s};" % (prefix, max(1, len(regs)), ",".join(map(str, regs)) or "0"))
    out.append("static const unsigned char %s_vals[%d] = {%s};" % (prefix, max(1, len(vals)), ",".join(map(str, vals)) or "0"))
    out.append("static const short %s_pos[%d] = {%s};" % (prefix, len(pos), ",".join(map(str, pos))))
    out.append("static const unsigned char %s_offs[%d] = {%s};" % (prefix, len(splits), ",".join(map(str, splits))))
    return "\n".join(out), len(regs)


def fnv64(data):
    h = 0xCBF29CE484222325
    for b in data:
        h = ((h ^ b) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def write_tables():
    path = os.path.join(ROOT, "app/src/main/cpp/generated/opl3_tables.h")
    fn = opl3_ref.FNUM
    text = [
        "/* Generated by tools/audio/prepare_opl3.py from tools/audio/opl3/opl3_ref.py - do not edit. */",
        "#ifndef THORTRACKER_OPL3_TABLES_H_",
        "#define THORTRACKER_OPL3_TABLES_H_",
        "",
        "#include <stdint.h>",
        "",
        "/* F-number of pitch C + i/768 octave (i = 0..767; pitch units = 1/64 semitone): for i < O3_FNUM_SPLIT at",
        " * block = octave - 1, from it at block = octave. 12-TET, A-4 = 440 Hz, chip rate 14318180 / 288 Hz. */",
        "#define O3_FNUM_SPLIT %d" % opl3_ref.FNUM_SPLIT,
        "static const uint16_t O3_FNUM[768] = {",
    ]
    for i in range(0, 768, 16):
        text.append("    " + ", ".join("%4d" % v for v in fn[i:i + 16]) + ",")
    text += ["};", "", "/* Vibrato: floor(127 sin(2 pi i / 64) + 0.5). */", "static const int8_t O3_SINE[64] = {"]
    for i in range(0, 64, 16):
        text.append("    " + ", ".join("%4d" % v for v in opl3_ref.SINE[i:i + 16]) + ",")
    text += ["};", "", "#endif /* THORTRACKER_OPL3_TABLES_H_ */", ""]
    with open(path, "w") as f:
        f.write("\n".join(text))
    print(path)


def byte_offsets(image):
    """Image offsets of the first mask, note, instrument and effect bytes, and of the first parameter of
    some effects, for the host test's single-byte corruptions."""
    img = opl3_ref.Image(image)
    found = {}
    starts = sorted({img.patterns[o][c] for o in range(img.orders) for c in range(9)})
    for start in starts:
        at = opl3_song.OFF_DATA + start
        m = image[at]
        while True:
            m = image[at]
            if m & 0x80:
                at += 1
                if at >= opl3_song.OFF_DATA + (image[14] | image[15] << 8):
                    break
                continue
            found.setdefault("MASK", at)
            at += 1
            if m & 1:
                found.setdefault("NOTE", at)
                at += 1
            if m & 2:
                found.setdefault("INST", at)
                at += 1
            for _ in range((m >> 2) & 7):
                found.setdefault("EFFECT", at)
                letter = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ"[image[at]]
                found.setdefault("PARAM_" + letter, at + 1)
                at += 2
            if at >= opl3_song.OFF_DATA + (image[14] | image[15] << 8):
                break
        if all(k in found for k in ("MASK", "NOTE", "INST", "EFFECT", "PARAM_B", "PARAM_C", "PARAM_E", "PARAM_F",
                                    "PARAM_I", "PARAM_K", "PARAM_M", "PARAM_W")):
            break
    return found


def write_fixture():
    song = opl3_song.test_song()
    images = {
        "song": opl3_song.build(song),
        "moved": opl3_song.build(song, relayout=True),
        "edited": opl3_song.build(opl3_song.edited_song()),
        "tempo": opl3_song.build(opl3_song.tempo_song()),
        "short": opl3_song.build(opl3_song.short_song()),
    }
    x2 = opl3_song.test_song()
    x2.multispeed = 2
    images["x2"] = opl3_song.build(x2)
    assert images["moved"] != images["song"]
    parts = ["/* Generated by tools/audio/prepare_opl3.py - do not edit. OPL3 host-test fixtures: the test song",
             " * (tools/audio/opl3/opl3_song.py) as images, and the reference player's (opl3_ref.py) writes. */",
             "#define OPL3_REF_TICKS %d" % TICKS]
    for name, data in images.items():
        parts.append(c_bytes("opl3_%s_image" % name, used(data)))
    total = 0
    for name in ("song", "edited", "tempo"):
        text, n = trace_arrays("opl3_ref_" + name, images[name])
        parts.append(text)
        total += n
    data, info = opl3_ref.vgm(opl3_ref.Image(images["song"]), VGM_MAX_TICKS)
    parts.append("#define OPL3_REF_VGM_SIZE %du" % len(data))
    parts.append("#define OPL3_REF_VGM_FNV 0x%016XULL" % fnv64(data))
    parts.append("#define OPL3_REF_VGM_TICKS %du" % info["ticks"])
    parts.append("#define OPL3_REF_VGM_LOOP_OFFSET %du" % info["loop_offset"])
    parts.append("#define OPL3_REF_VGM_LOOP_SAMPLES %du" % info["loop_samples"])
    parts.append("#define OPL3_REF_VGM_SAMPLES %du" % info["samples"])
    for key, offset in sorted(byte_offsets(images["song"]).items()):
        parts.append("#define OPL3_OFFSET_%s %d" % (key, offset))
    path = os.path.join(ROOT, "app/src/test/cpp/opl3_test_song.h")
    with open(path, "w") as f:
        f.write("\n".join(parts) + "\n")
    print("%s (%d reference writes; VGM %d bytes, %d ticks, loop %d samples)" % (path, total, len(data), info["ticks"],
                                                                                 info["loop_samples"]))
    return images


CPP = os.path.join(ROOT, "app/src/main/cpp")
KOTLIN = os.path.join(ROOT, "core/src/commonMain/kotlin/org/thortracker/backend/Opl3PlayerImage.kt")


def c_constants():
    """#define O3*_NAME values and enum O3_FX_* codes of the OPL3 engine headers, evaluated."""
    values = {}
    for name in ("opl3/opl3_image.h", "opl3/opl3_player.h", "opl3/opl3_machine.h"):
        with open(os.path.join(CPP, name)) as f:
            for line in f:
                m = re.match(r"#define (O3[MP]?_\w+) +([^/]+?)\s*(/\*.*)?$", line.rstrip())
                if m and not m.group(1).endswith("_H_"):
                    expr = re.sub(r"\b(\d+|0x[0-9A-Fa-f]+)u\b", r"\1", m.group(2))
                    values[m.group(1)] = eval(expr, {}, dict(values))
                m = re.match(r"\s+(O3_FX_\w+) = (\d+),", line)
                if m:
                    values[m.group(1)] = int(m.group(2))
    return values


def loader_problems():
    """Every reason string o3_load_image can report (opl3_image.c), in source order."""
    with open(os.path.join(CPP, "opl3/opl3_image.c")) as f:
        text = f.read()
    found = []
    for m in re.finditer(r'(?:fail\(image, |why = )"([^"]+)"', text):
        if m.group(1) not in found:
            found.append(m.group(1))
    return found


def gd3_strings():
    with open(os.path.join(CPP, "opl3/opl3_vgm.c")) as f:
        text = f.read()
    return {k: re.search(r'#define GD3_%s "([^"]+)"' % k, text).group(1) for k in ("SYSTEM", "CONVERTER")}


def write_kotlin():
    c = c_constants()
    fx = {k[len("O3_FX_"):]: v for k, v in c.items() if k.startswith("O3_FX_")}
    letters = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ"
    gd3 = gd3_strings()

    def kt(name, key=None):
        return "    const val %s = %s" % (name, c[key or "O3_" + name])

    lines = [
        "// GENERATED by tools/audio/prepare_opl3.py from the engine headers (app/src/main/cpp/opl3) -- do not edit.",
        "package org.thortracker.backend",
        "",
        "/**",
        " * The OPL3 system's native contract: Thor Tracker's own player on a YMF262 (Nuked-OPL3), engine `\"opl3-fm\"`.",
        " * The image layout the lowering writes, its limits, the effect codes and the loader's rejection messages, as",
        " * `opl3_image.h`, `opl3_player.h` and `opl3_machine.h` define them (`docs/AUDIO_ENGINE.md`, \"OPL3\": the",
        " * specification). All multi-byte fields are little-endian.",
        " */",
        "object Opl3PlayerImage {",
        "    /** Native engine id ([org.thortracker.system.PlaybackEngine.id]). */",
        '    const val ENGINE_ID = "opl3-fm"',
        "",
        "    /** One fixed-size image per song. */",
        kt("IMAGE_SIZE"),
        '    const val MAGIC = "TTO3"',
        kt("LAYOUT"),
        "",
        "    /** Header field offsets (64-byte header; bytes 16..63 zero). */",
    ]
    for name in ("H_MAGIC", "H_LAYOUT", "H_MULTISPEED", "H_SPEED", "H_DEPTH", "H_ORDERS", "H_LOOP", "H_INSTRUMENTS",
                 "H_SHAPES", "H_DATA_SIZE", "HEADER_SIZE"):
        lines.append(kt(name))
    lines += [
        "",
        "    /** Header byte [H_DEPTH]: register 0xBD bits (deep tremolo 4.8 dB, deep vibrato 14 cents); others 0. */",
        "    const val DEPTH_TREMOLO = 0x80",
        "    const val DEPTH_VIBRATO = 0x40",
        "",
        "    /**",
        "     * Fixed tables: rows of order o at [OFF_ROWS] + o (1..255, 0 = 256); the pattern of (order o, channel c)",
        "     * as a u16 offset into the data region at [OFF_ORDERS] + 2 (9 o + c); instrument slot n (1..64) at",
        "     * [OFF_INSTRUMENTS] + [INSTRUMENT_SIZE] (n - 1); chord shape k (1..64) at [OFF_SHAPES] + 4 (k - 1) (up to",
        "     * four s8 intervals -48..48, non-zero first); pattern data from [OFF_DATA], [DATA_CAPACITY] bytes.",
        "     */",
    ]
    for name in ("OFF_ROWS", "OFF_ORDERS", "OFF_INSTRUMENTS", "INSTRUMENT_SIZE", "OFF_SHAPES", "OFF_DATA"):
        lines.append(kt(name))
    lines.append("    const val DATA_CAPACITY = %d" % c["O3_DATA_CAPACITY"])
    lines.append("    const val SHAPE_SIZE = 4")
    lines += [
        "",
        "    /**",
        "     * Instrument record: flags ([FLAG_DEFINED], [FLAG_FOUR_OP]; all-zero = no instrument), algorithm (2-op 0 FM,",
        "     * 1 additive; 4-op 0..3 = CNT_A * 2 + CNT_B), operator-1 feedback 0..7, byte 3 zero, operator k (0..3) at",
        "     * [I_OPS] + 5 k = registers 0x20, 0x40, 0x60, 0x80, 0xE0 (wave 0..7; 2-op: operators 3, 4 zero), drum sweep",
        "     * start/end (s8 semitones -96..96 from the note) and speed (1/16 semitone per tick, 0 = none), bytes 27..31 zero.",
        "     */",
    ]
    for name in ("I_FLAGS", "I_ALG", "I_FEEDBACK", "I_OPS", "I_SWEEP_START", "I_SWEEP_END", "I_SWEEP_SPEED",
                 "FLAG_DEFINED", "FLAG_FOUR_OP"):
        lines.append(kt(name))
    lines += [
        "    const val OPERATOR_BYTES = 5",
        "    const val SWEEP_LIMIT = 96",
        "    const val CHORD_INTERVAL_LIMIT = 48",
        "",
        "    /**",
        "     * Pattern rows: [RUN] | k = k + 1 empty rows (k 0..127, [MAX_RUN] rows at most); else a mask byte: [MASK_NOTE]",
        "     * (note byte follows), [MASK_INSTRUMENT] (slot byte follows), effect count 0..4 at bits 2-4 ([MASK_EFFECT_SHIFT]);",
        "     * then the note (0..95 absolute, [NOTE_OFF]), the slot, and per effect column code (0..35 = '0'..'9', 'A'..'Z')",
        "     * and parameter. Each (order, channel) decodes exactly rows(order) rows inside the used data.",
        "     */",
        "    const val RUN = 0x80",
        "    const val MAX_RUN = 128",
        "    const val MASK_NOTE = 0x01",
        "    const val MASK_INSTRUMENT = 0x02",
        "    const val MASK_EFFECT_SHIFT = 2",
        kt("NOTE_OFF"),
        kt("NOTES"),
        "",
        "    /** Limits. Channels 1-6 (index 0..5) may play 4-op instruments, 7-9 are 2-op only. */",
        kt("CHANNELS"),
        "    const val FOUR_OP_CHANNELS = 6",
        kt("VOICES"),
        kt("MAX_ORDERS"),
        kt("MAX_INSTRUMENTS"),
        kt("MAX_SHAPES"),
        kt("MAX_EFFECTS"),
        kt("MAX_MULTISPEED"),
        "    /** Chord voices: the pool shared by every channel's Hxy/Kxx notes (2-op only). */",
        kt("POOL", "O3P_POOL"),
        kt("MAX_CHORD", "O3P_MAX_CHORD"),
        "",
        "    /** Pitch units: 1/64 semitone, 0 = C-0, note n = 64 n; [PITCH_MAX] just below C-8. Fine pitch (Pxx, audition) -128..127. */",
        "    const val PITCH_UNITS_PER_SEMITONE = 64",
        kt("PITCH_MAX", "O3P_PITCH_MAX"),
        "",
        "    /** Effect codes (column code byte); [EFFECT_LETTERS][code] is the name. */",
        '    const val EFFECT_LETTERS = "%s"' % letters,
    ]
    for name, v in sorted(fx.items(), key=lambda kv: kv[1]):
        lines.append("    const val FX_%s = %d // %s" % (name, v, letters[v]))
    lines += [
        "",
        "    /** Chip and timing: YMF262 clock, native rate = [CLOCK] / [NATIVE_DIVIDER]; one tick = 1/60 s / multispeed. */",
        kt("CLOCK", "O3M_CLOCK"),
        kt("NATIVE_DIVIDER", "O3M_NATIVE_DIVIDER"),
        "    /** Seek: [org.thortracker.system.PlaybackEngine.seekTicks] budget; the chip is clocked through the last [PREROLL_TICKS] x multispeed ticks. */",
        "    const val SEEK_TICKS = 12000",
        kt("PREROLL_TICKS", "O3M_PREROLL_TICKS"),
        "",
        "    /** VGM export (native `o3_export_vgm`): GD3 system and converter names the file carries. */",
        '    const val GD3_SYSTEM = "%s"' % gd3["SYSTEM"],
        '    const val GD3_CONVERTER = "%s"' % gd3["CONVERTER"],
        "",
        "    /**",
        "     * F-number of pitch C + i/768 octave (i = pitch mod 768): below [FNUM_SPLIT] at block = octave - 1, from it at",
        "     * block = octave (block -1 = block 0 with the F-number halved). Frequency = F-number x native rate / 2^(20 - block).",
        "     */",
        "    const val FNUM_SPLIT = %d" % opl3_ref.FNUM_SPLIT,
        "    val FNUM: IntArray get() = intArrayOf(",
    ]
    for i in range(0, 768, 24):
        lines.append("        " + ", ".join(str(v) for v in opl3_ref.FNUM[i:i + 24]) + ",")
    lines += [
        "    )",
        "",
        "    /**",
        "     * Every reason the native loader (`o3_load_image`) rejects an image with (`opl3_image.c` order). A song the Kotlin",
        "     * validator accepts must never produce one; mirror the checks with user-facing messages.",
        "     */",
        "    val LOADER_PROBLEMS: List<String> = listOf(",
    ]
    for s in loader_problems():
        lines.append('        "%s",' % s.replace('"', '\"'))
    lines += ["    )", "}", ""]
    with open(KOTLIN, "w") as f:
        f.write("\n".join(lines))
    print(KOTLIN)


if __name__ == "__main__":
    write_tables()
    write_fixture()
    write_kotlin()
