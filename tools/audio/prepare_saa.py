def write_tables():
    text = [
        "/* Generated by tools/audio/prepare_saa.py from tools/audio/saa/saa_ref.py - do not edit. */",
        "#ifndef THORTRACKER_SAA_TABLES_H_",
        "#define THORTRACKER_SAA_TABLES_H_",
        "",
        "#include <stdint.h>",
        "",
        "/* SA_DIV_*[r] = floor(K / (512 * 440 * 2^((r/64 - 57)/12)) * 256 + 0.5): the divider 511 - N of C-0 + r/64",
        " * semitones at octave 0 in Q8, for the SAM Coupe's clock K = 8000000 Hz and the CMS's 7159090 Hz. Octave and",
        " * offset of pitch p (docs/AUDIO_ENGINE.md \"SAA1099: Player\"): k = p / 768, t = SA_DIV[p % 768]; t >= 131072:",
        " * O = k - 1, d = (t + 256) >> 9; else O = k, d = (t + 128) >> 8 (d >= 512: as t >= 131072); N = 511 - d,",
        " * clamped to O 0 N 0 .. O 7 N 255. */",
    ]
    for name, table in (("SA_DIV_SAM", saa_ref.DIV_SAM), ("SA_DIV_CMS", saa_ref.DIV_CMS)):
        text.append("static const uint32_t %s[768] = {" % name)
        for i in range(0, 768, 12):
            text.append("    " + ", ".join("%7d" % v for v in table[i:i + 12]) + ",")
        text += ["};", ""]
    text += ["/* Vibrato: floor(127 sin(2 pi i / 64) + 0.5). */", "static const int8_t SA_SINE[64] = {"]
    for i in range(0, 64, 16):
        text.append("    " + ", ".join("%4d" % v for v in saa_ref.SINE[i:i + 16]) + ",")
    text += ["};", "", "#endif /* THORTRACKER_SAA_TABLES_H_ */", ""]
    os.makedirs(os.path.dirname(TABLES), exist_ok=True)
    with open(TABLES, "w") as f:
        f.write("\n".join(text))
    print(TABLES)


