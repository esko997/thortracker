def c_constants():
    """#define SA*_NAME values and enum SA_FX_* codes of the SAA1099 engine headers, evaluated."""
    values = {}
    for name in HEADERS:
        with open(os.path.join(CPP, name), encoding="utf-8") as f:
            for line in f:
                m = re.match(r"#define ((?:SA|SAP|SAAM|SAC)_\w+)\s+(\"[^\"]*\"|[^/]+?)\s*(/\*.*)?$", line.rstrip())
                if m and not m.group(1).endswith("_H_") and "(" not in m.group(1):
                    expr = re.sub(r"\b(\d+|0x[0-9A-Fa-f]+)[uU][lL]*\b", r"\1", m.group(2))
                    expr = re.sub(r"\(\s*(?:u?int\d+_t|unsigned|int)\s*\)", "", expr)
                    try:
                        values[m.group(1)] = eval(expr, {}, dict(values))
                    except Exception:  # a macro that is not a constant (function-like or using a type)
                        pass
                m = re.match(r"\s+(SA_FX_\w+)\s*=\s*(\d+)\s*,", line)
                if m:
                    values[m.group(1)] = int(m.group(2))
    return values


def strip_c_comments(text):
    """C source without its comments (string and character literals kept intact)."""
    out, i, n = [], 0, len(text)
    while i < n:
        ch = text[i]
        if ch in "\"'":
            j = i + 1
            while j < n and text[j] != ch:
                j += 2 if text[j] == "\\" else 1
            out.append(text[i:j + 1])
            i = j + 1
        elif text.startswith("/*", i):
            end = text.find("*/", i + 2)
            i = n if end < 0 else end + 2
            out.append(" ")
        elif text.startswith("//", i):
            end = text.find("\n", i)
            i = n if end < 0 else end
        else:
            out.append(ch)
            i += 1
    return "".join(out)


def loader_problems():
    """Every reason sa_load_image reports: the string literals passed to saa_image.c's rejection helper (its first
    string argument, outside comments), in source order, duplicates removed."""
    path = os.path.join(CPP, "saa/saa_image.c")
    with open(path, encoding="utf-8") as f:
        text = strip_c_comments(f.read())
    found = []
    for m in re.finditer(r'\b(?:reject|bad|fail)\w*\(\s*(?:\w+\s*,\s*)?"((?:[^"\\]|\\.)*)"', text):
        reason = m.group(1).replace('\\"', '"').replace("\\\\", "\\")
        if reason not in found:
            found.append(reason)
    if not found:
        sys.exit("%s: no rejection reasons found (expected reject(image, \"reason\", offset) calls)" % path)
    return found


def kt_string(s):
    return '"%s"' % s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$")


