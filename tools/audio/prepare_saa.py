def trace_arrays(name, image_bytes):
    batches = saa_ref.trace(saa_ref.Image(image_bytes), TICKS)
    offsets, chips, regs, vals, pos = [0], [], [], [], []
    for _, p, writes in batches:
        for chip, reg, val in writes:
            chips.append(chip)
            regs.append(reg)
            vals.append(val)
        offsets.append(len(chips))
        pos.extend(p if p is not None else (-1, -1, -1))
    assert len(offsets) == TICKS + 2 and len(pos) == 3 * (TICKS + 1)
    prefix = "saa_ref_" + name
    out = [
        c_array("int", prefix + "_offsets", "SAA_REF_TICKS + 2", offsets, 16),
        c_array("unsigned char", prefix + "_chips", None, chips, 40),
        c_array("unsigned char", prefix + "_regs", None, regs, 32),
        c_array("unsigned char", prefix + "_vals", None, vals, 32),
        c_array("short", prefix + "_pos", "3 * (SAA_REF_TICKS + 1)", pos, 30),
    ]
    return "\n".join(out), len(chips)


def byte_offsets(image):
    """Absolute image offsets for the host test's single-byte corruptions: the first row mask, note, instrument and
    effect code bytes, the parameter of the first B, C, E, F, M, N and Y, slot 02's volume envelope header (it has a
    release point), the first value of slot 06's mixer envelope and slot 1's record."""
    img = saa_ref.Image(image)
    found = {}
    for o in range(img.orders):
        for c in range(img.channels):
            at, r = saa_ref.OFF_DATA + img.patterns[o][c], 0
            while r < img.rows[o]:
                m = image[at]
                if m & 0x80:
                    r += (m & 0x7F) + 1
                    at += 1
                    continue
                found.setdefault("MASK", at)
                at += 1
                if m & 1:
                    found.setdefault("NOTE", at)
                    at += 1
                if m & 2:
                    found.setdefault("INST", at)
                    at += 1
                for _ in range((m >> 2) & 7):
                    found.setdefault("EFFECT", at)
                    letter = LETTERS[image[at]]
                    if letter in "BCEFMNY":
                        found.setdefault("PARAM_" + letter, at + 1)
                    at += 2
                r += 1
    rec1 = saa_ref.OFF_INSTRUMENTS
    rec2 = saa_ref.OFF_INSTRUMENTS + saa_ref.INSTRUMENT_SIZE
    rec6 = saa_ref.OFF_INSTRUMENTS + 5 * saa_ref.INSTRUMENT_SIZE
    volume2 = saa_ref.u16(image, rec2 + saa_ref.I_VOLUME)
    mixer6 = saa_ref.u16(image, rec6 + saa_ref.I_MIXER)
    assert img.envelope(2, 0).release >= 0, "slot 02's volume envelope must have a release point"
    assert img.envelope(6, 3) is not None, "slot 06 must have a mixer envelope"
    found["ENV_VOLUME"] = saa_ref.OFF_DATA + volume2
    found["ENV_MIXER"] = saa_ref.OFF_DATA + mixer6 + saa_ref.ENV_HEADER
    found["INSTRUMENT"] = rec1
    for key in ("MASK", "NOTE", "INST", "EFFECT", "PARAM_B", "PARAM_C", "PARAM_E", "PARAM_F", "PARAM_M", "PARAM_N",
                "PARAM_Y"):
        assert key in found, key
    return found


def vgm_defines(prefix, image_bytes):
    data, info = saa_ref.vgm(saa_ref.Image(image_bytes), VGM_MAX_TICKS)
    assert info["looped"], prefix + ": the test song must reach a repeating loop pass"
    return [
        "#define %s_SIZE %du" % (prefix, len(data)),
        "#define %s_FNV 0x%016XULL" % (prefix, fnv64(data)),
        "#define %s_TICKS %du" % (prefix, info["ticks"]),
        "#define %s_LOOP_OFFSET %du" % (prefix, info["loop_offset"]),
        "#define %s_LOOP_SAMPLES %du" % (prefix, info["loop_samples"]),
        "#define %s_SAMPLES %du" % (prefix, info["samples"]),
    ], data, info


def write_fixture():
    images = {
        "sam": saa_song.build(saa_song.test_song()),
        "cms": saa_song.build(saa_song.cms_song()),
        "moved": saa_song.build(saa_song.test_song(), relayout=True),
        "edited": saa_song.build(saa_song.edited_song()),
        "tempo": saa_song.build(saa_song.tempo_song()),
        "short": saa_song.build(saa_song.short_song()),
        "x2": saa_song.build(saa_song.x2_song()),
        "env_edit": saa_song.build(saa_song.env_edit_song()),
    }
    for name, data in images.items():
        saa_ref.validate(data)  # every fixture is a valid image
    assert images["moved"] != images["sam"]
    assert images["env_edit"] != images["sam"]
    parts = [
        "/* Generated by tools/audio/prepare_saa.py - do not edit. SAA1099 host-test fixtures: the test songs",
        " * (tools/audio/saa/saa_song.py) as images, the reference player's (tools/audio/saa/saa_ref.py) batches",
        " * (the reset batch, then one per tick; positions before each batch, -1 for the reset), its VGM facts and",
        " * byte offsets for single-byte corruptions. Images stop at their last non-zero byte: zero-pad to 65536. */",
        "#define SAA_REF_TICKS %d" % TICKS,
        "#define SAA_ENV_EDIT_SLOT %d" % saa_song.ENV_EDIT_SLOT,
    ]
    for name, data in images.items():
        parts.append(c_array("unsigned char", "saa_%s_image" % name, None, used(data), 32))
    total = 0
    for name in ("sam", "cms", "edited", "tempo"):
        text, n = trace_arrays(name, images[name])
        parts.append(text)
        total += n
    defines, data, info = vgm_defines("SAA_SAM_REF_VGM", images["sam"])
    parts += defines
    cms_defines, cms_data, cms_info = vgm_defines("SAA_CMS_REF_VGM", images["cms"])
    parts += cms_defines
    for key, offset in sorted(byte_offsets(images["sam"]).items()):
        parts.append("#define SAA_OFFSET_%s %d" % (key, offset))
    with open(FIXTURE, "w") as f:
        f.write("\n".join(parts) + "\n")
    print("%s (%d reference writes; SAM VGM %d bytes, %d ticks, loop %d samples; CMS VGM %d bytes, %d ticks)"
          % (FIXTURE, total, len(data), info["ticks"], info["loop_samples"], len(cms_data), cms_info["ticks"]))


