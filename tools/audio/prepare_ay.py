def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    return re.sub(r"//[^\n]*", " ", text)


def c_constants():
    """#define AY*_NAME values (numbers, expressions of earlier ones, strings) and enum AY_FX_* codes of the engine
    headers, evaluated."""
    values = {}
    for name in ("ay/ay_image.h", "ay/ay_player.h", "ay/ay_machine.h"):
        with open(os.path.join(CPP, name)) as f:
            text = strip_comments(f.read())
        for line in text.splitlines():
            m = re.match(r"\s*#define (AY\w*_\w+)\s+(.+?)\s*$", line)
            if m and not m.group(1).endswith("_H_"):
                expr = re.sub(r"\b(\d+|0x[0-9A-Fa-f]+)[uUlL]+\b", r"\1", m.group(2))
                expr = re.sub(r"\((?:int|unsigned|uint\d+_t|int\d+_t|size_t)\)", "", expr)
                try:
                    values[m.group(1)] = eval(expr, {}, dict(values))
                except (NameError, SyntaxError, TypeError):
                    pass
            for m in re.finditer(r"\b(AY_FX_\w+)\s*=\s*(0x[0-9A-Fa-f]+|\d+)", line):
                values[m.group(1)] = int(m.group(2), 0)
    return values


def loader_problems():
    """Every reason string in ay_image.c (comments and the magic left out), in source order; must be exactly the
    reasons the reference loader reports."""
    with open(os.path.join(CPP, "ay/ay_image.c")) as f:
        text = strip_comments(f.read())
    found = []
    for line in text.splitlines():
        if line.lstrip().startswith("#"):
            continue
        for s in re.findall(r'"((?:[^"\\]|\\.)*)"', line):
            if s != "TTAY" and s not in found:
                found.append(s)
    if set(found) != set(ay_ref.LOADER_REASONS):
        raise SystemExit("ay_image.c's reasons differ from ay_ref.LOADER_REASONS: only in C %s, only in the reference %s"
                         % (sorted(set(found) - set(ay_ref.LOADER_REASONS)),
                            sorted(set(ay_ref.LOADER_REASONS) - set(found))))
    return found


