def used(image):
    """Bytes up to the end of the data (the rest of an image is zero)."""
    end = ay_song.OFF_DATA + u16(image, 14)
    assert not any(image[end:])
    return image[:end]


def tick_at(image, position):
    """Index of the first tick whose position (before it) is `position`, in straight play."""
    for k, (pos, _) in enumerate(ay_ref.trace(image, TICKS)):
        if pos == position:
            return k
    raise SystemExit("the test song never reaches %s" % (position,))


def trace_arrays(name, tr):
    first, writes, positions = [0], [], []
    for pos, w in tr:
        for reg, val in w:
            writes += [reg, val]
        first.append(len(writes) // 2)
        positions.extend(pos)
    parts = [c_array("uint32_t", name + "_first", first),
             c_array("uint8_t", name + "_writes", writes, 32),
             c_array("uint16_t", name + "_positions", positions, 36)]
    return "\n".join(parts), "{%du, %s_first, %s_writes, %s_positions}" % (len(tr), name, name, name)


def instrument_base(slot):
    return ay_song.OFF_INSTRUMENTS + ay_song.INSTRUMENT_SIZE * (slot - 1)


def envelope_at(image, slot, kind):
    off = u16(image, instrument_base(slot) + 6 + 2 * kind)
    assert off != 0xFFFF, (slot, kind)
    return ay_song.OFF_DATA + off


def effect_bytes(image):
    """Image offset of the first code byte of each effect letter, and of the first row's mask, note and instrument,
    walking the patterns in data order."""
    img = ay_ref.Image(image)
    found = {}
    for o in range(img.orders):
        for c in range(ay_ref.CHANNELS):
            at = ay_ref.OFF_DATA + img.patterns[o][c]
            rows = 0
            while rows < img.rows[o]:
                m = image[at]
                if m & 0x80:
                    rows += (m & 0x7F) + 1
                    at += 1
                    continue
                if m & 1 and m & 2:
                    found.setdefault("mask", at)
                    found.setdefault("note", at + 1)
                    found.setdefault("instrument", at + 2)
                at += 1 + (m & 1) + ((m >> 1) & 1)
                for _ in range((m >> 2) & 7):
                    found.setdefault(ay_ref.LETTERS[image[at]], at)
                    at += 2
                rows += 1
    return found


def corruptions(image):
    """Single-byte corruptions of `image` (AY_TEST_SONG[0]) with the reason and byte the loader reports, each
    checked against the reason it is meant to provoke."""
    fx = effect_bytes(image)
    envs = [u16(image, instrument_base(s) + 6 + 2 * k) for s in range(1, 65) for k in range(5)
            if image[instrument_base(s)]]
    last_env = ay_song.OFF_DATA + max(o for o in envs if o != 0xFFFF)
    assert u16(image, last_env) < 255
    first_pattern = ay_song.OFF_ORDERS
    cases = [
        (0, ord("X"), "not an AY image (magic)"),
        (4, 2, "unknown layout"),
        (5, 4, "variant must be 0 (ZX Spectrum 128), 1 (MSX), 2 (Atari ST) or 3 (Amstrad CPC)"),
        (6, 0, "speed must be 1..255"),
        (7, 1, "header reserved byte 7"),
        (8, 0, "order count must be 1..256"),
        (10, 4, "loop order past the last order"),
        (12, 65, "instrument count above 64"),
        (13, 1, "header reserved byte 13"),
        (15, 0xF1, "data size above the region"),
        (40, 1, "header reserved bytes 16..63"),
        (ay_song.OFF_ROWS + 4, 1, "rows of an order past the order count"),
        (ay_song.OFF_ORDERS + 6 * 4 + 1, 1, "patterns of an order past the order count"),
        (1900, 1, "reserved bytes 1856..2047"),
        (12, 17, "instrument record past the instrument count"),
        (instrument_base(1), 0x02, "instrument flags"),
        (instrument_base(1), 0xC2, "instrument flags"),
        (instrument_base(4), 0x84, "sync needs the auto envelope period"),
        (instrument_base(2) + 1, 5, "envelope shape must be 0 or 8..15"),
        (instrument_base(2) + 2, 8, "auto octave outside -8..7"),
        (instrument_base(4) + 2, 1, "auto octave on a manual-period instrument"),
        (instrument_base(1) + 3, 1, "instrument reserved byte 3"),
        (instrument_base(2) + 4, 1, "manual period on an auto-period instrument"),
        (instrument_base(2) + 6 + 2 * 3 + 1, 0xF0, "envelope outside the data size"),
        (envelope_at(image, 2, 3), 0, "envelope length outside 1..256"),
        (last_env, 0xFF, "envelope outside the data size"),
        (envelope_at(image, 7, 1) + 2, 3, "envelope loop past its end"),
        (envelope_at(image, 7, 1) + 5, 0, "release point on a non-volume envelope"),
        (envelope_at(image, 6, 0) + 4, 5, "volume release point needs a loop before it"),
        (envelope_at(image, 6, 0) + 6, 16, "volume envelope value outside 0..15"),
        (envelope_at(image, 7, 1) + 6, 64, "arpeggio or pitch envelope value outside -64..63"),
        (envelope_at(image, 2, 3) + 6, 4, "mixer envelope value outside 0..3"),
        (envelope_at(image, 8, 4) + 6, 32, "noise envelope value outside 0..31"),
        (instrument_base(8) + 16, 97, "sweep start/end outside -96..96 semitones"),
        (instrument_base(1) + 19, 1, "instrument reserved bytes 19..31"),
        (first_pattern + 1, 0xF0, "pattern offset past the data size"),
        (fx["mask"], 0x60, "row mask byte"),
        (fx["note"], 96, "note byte"),
        (fx["instrument"], 0, "row names an instrument the image does not define"),
        (fx["instrument"], 19, "row names an instrument the image does not define"),
        (fx["0"], 36, "effect code above Z"),
        (fx["0"], 5, "unknown effect code"),
        (fx["B"] + 1, 4, "Bxx jumps past the last order"),
        (fx["C"] + 1, 0x10, "Cxx volume above 0F"),
        (fx["E"] + 1, 0x05, "Exx shape must be 00 or 08..0F"),
        (fx["F"] + 1, 0x00, "F00: speed must be 1..FF"),
        (fx["J"] + 1, 0x08, "Jxx octave must be 00..07 or F8..FF"),
        (fx["V"] + 1, 0x04, "Vxx mixer above 03"),
        (fx["W"] + 1, 0x20, "Wxx noise period above 1F"),
    ]
    out = []
    for offset, value, reason in cases:
        assert image[offset] != value, (offset, reason)
        bad = bytearray(image)
        bad[offset] = value
        try:
            ay_ref.Image(bytes(bad))
        except ay_ref.ImageError as e:
            if e.problem != reason:
                raise SystemExit("corruption at %d = %d: loader says %r, meant %r" % (offset, value, e.problem, reason))
            out.append((offset, value, e.problem, e.offset))
            continue
        raise SystemExit("corruption at %d = %d (%s) loads" % (offset, value, reason))
    return out


def c_string(s):
    return '"%s"' % s.replace("\\", "\\\\").replace('"', '\\"')


